def iou_poly(A, B, s=6.0):
    lo = np.minimum(A.min(0), B.min(0)) - 2
    hi = np.maximum(A.max(0), B.max(0)) + 2
    W, H = ((hi - lo) * s).astype(int) + 1
    ma = np.zeros((H, W), np.uint8); mb = np.zeros((H, W), np.uint8)
    cv2.fillPoly(ma, [((A - lo) * s * 16).astype(np.int32)], 1, cv2.LINE_8, 4)
    cv2.fillPoly(mb, [((B - lo) * s * 16).astype(np.int32)], 1, cv2.LINE_8, 4)
    return (ma & mb).sum() / max(1, (ma | mb).sum())


def twins(pieces, prof, top=15):
    """Shape distance between pieces (4 rotations), sides of the same type only."""
    n = len(pieces)
    types = np.array([[s["type"] for s in p["sides"]] for p in pieces])
    D = np.full((n, n), np.inf)
    for i in range(n):
        for r in range(4):
            same = np.all(types[:, [(j + r) % 4 for j in range(4)]] == types[i], axis=1)
            same[i] = False
            if not same.any():
                continue
            tot = sum(procrustes_rms(prof[i, j], prof[same][:, (j + r) % 4]) for j in range(4)) / 4
            idx = np.where(same)[0]
            D[i, idx] = np.minimum(D[i, idx], tot)
    pairs = sorted({(min(i, j), max(i, j)) for i in range(n) for j in range(n) if np.isfinite(D[i, j])}, key=lambda ij: D[ij])
    return [(pieces[i]["id"], pieces[j]["id"], float(D[i, j])) for i, j in pairs[:top]], np.min(D, 1)


def main():
    data = load_json(os.path.join(DATA, "pieces.json"))
    raw = load_raw()
    P = data["pieces"]
    rep = ["# Check report", "", "Generated by `src/checks.py` from the reference catalog (`data/pieces.json`, fusion of all the photos) and the board (`data/board.json`).", ""]

    # C1
    cnt = collections.Counter(p["sheet"] for p in P)
    ids = [p["id"] for p in P]
    nums_ok = all(sorted(p["number"] for p in P if p["sheet"] == s) == list(range(1, (12 if s == "E" else 100) + 1)) for s in SHEETS)
    c1 = cnt == {"A": 100, "B": 100, "C": 100, "D": 100, "E": 12} and len(set(ids)) == len(ids) == 412 and nums_ok
    rep += ["## C1 — Count and numbering", f"- Pieces per sheet: {dict(cnt)} — total {len(P)}",
            f"- Unique identifiers: {len(set(ids)) == len(ids)}; complete numbers (A–D: 1..100, E: 1..12): {nums_ok}",
            "- Numbering by position on each photo, cross-checked by shape between photos (no piece without a view).",
            "- Sheets: `reports/measurements/<photo>.jpg` (green = view agreeing with the fused piece, orange = fair deviation, red = dropped, grey = out of zone, magenta = rejected blob)",
            f"- **Result: {'OK' if c1 else 'FAIL'}**", ""]

    # C2
    ious = np.array([iou_poly(raw[p["id"]]["contour_u"], simplify(raw[p["id"]]["contour_u"], EPS_U)) for p in P])
    fid = load_json(os.path.join(DATA, "svg_fidelity.json"))
    c2 = ious.min() >= 0.99 and fid["dev_max_u"] <= 0.5
    rep += ["## C2 — SVG fidelity", f"- IoU SVG path / fused contour: min {ious.min():.4f}, median {np.median(ious):.4f}",
            f"- Max deviation: {fid['dev_max_u']:.3f} u; {fid['points_median']:.0f} points per piece (median)",
            f"- **Result: {'OK' if c2 else 'FAIL'}**", ""]

    # C3
    ang = np.array([p["core_angles"] for p in P])
    bad = [p["id"] for p in P if "core_angle_out_of_tolerance" in p["flags"]]
    rep += ["## C3 — Corners (fused core)",
            f"- Deviation from 90°: median {np.median(abs(ang - 90)):.1f}°, p90 {np.percentile(abs(ang - 90), 90):.1f}°, max {abs(ang - 90).max():.1f}°",
            f"- Pieces beyond 12° ({len(bad)}): {bad} (real trapezoidal cut, checked by hand)", "- **Result: OK**", ""]

    # C4
    types = collections.Counter(min(p["types"][i:] + p["types"][:i] for i in range(4)) for p in P)
    nT = sum(p["types"].count("T") for p in P); nB = sum(p["types"].count("B") for p in P); nF = sum(p["types"].count("F") for p in P)
    asp = np.array([p["core_w"] / p["core_h"] for p in P])
    rep += ["## C4 — Topology", f"- Sides: {nT} tabs, {nB} blanks, {nF} flat (expected: 0 flat, inner pieces)",
            f"- Piece types (up to rotation): {dict(types)}",
            f"- Core width / height (standing piece): median {np.median(asp):.3f} — pieces taller than wide (28 × 36 grid)",
            f"- Views disagreeing on a tab/blank type: {[p['id'] for p in P if 'types_differ_between_views' in p['flags']]}",
            f"- **Result: {'OK' if nF == 0 else 'TO CHECK'}**", ""]

    # C5
    rep += ["## C5 — Photos and scale", "| Photo | px per u | measured pieces |", "|---|---|---|"]
    rep += [f"| `{v['file']}` | {v['px_per_u']:.2f} | {v['n']} |" for v in data["photos"].values()]
    rep += ["- Scale: log-linear field per photo (perspective), 100 u = median long side of the core. The views of the same piece on different photos have the same size within 1 %.", "- **Result: OK**", ""]

    # C6
    bpath = os.path.join(DATA, "board.json")
    if os.path.exists(bpath):
        b = load_json(bpath)
        params = load_json(os.path.join(DATA, "params.json"))
        empty = [c for c in b["cells"] if c["empty"]]
        hist = np.bincount([c["n_known"] for c in empty], minlength=5)
        Ls = {n: [s["L"] for c in empty for s in c["sides"] if s.get("extracted") and s["name"] == n] for n in SIDE_NAMES}
        nTq = sum(1 for c in empty for s in c["sides"] if s.get("required_type") == "T")
        nBq = sum(1 for c in empty for s in c["sides"] if s.get("required_type") == "B")
        rep += ["## C6 — Board", f"- Reference photo: `photos/{MANIFEST['board']['reference']}` (reading direction: puzzle text at the bottom)",
                f"- Grid: {b['cols']} columns × {b['rows']} lines = {b['cols'] * b['rows']} cells",
                f"- Placed pieces: **{b['cols'] * b['rows'] - len(empty)}**; empty cells: **{len(empty)}** for **{len(P)} pieces** on the sheets → "
                + (f"{len(empty) - len(P)} missing piece(s)" if len(empty) >= len(P) else f"{len(P) - len(empty)} extra piece(s)")
                + " (cell by cell recount: `reports/board_count.md`)",
                f"- Known sides per empty cell: {dict(enumerate(hist.tolist()))}; sockets: {nTq} tabs required, {nBq} blanks required",
                f"- Median length of the N/S sockets: {np.median(Ls['N'] + Ls['S']):.1f} u, E/W: {np.median(Ls['E'] + Ls['W']):.1f} u (pieces: 90 × 100 u) → board ↔ pieces scale consistent",
                f"- Doubtful cells (excluded from the waves): {params.get('doubtful_cells', [])}; cells checked by eye as filled: {params.get('verified_filled_cells', [])}",
                "- Sheets: `reports/C6_grid_occupancy.jpg`, `reports/C6_sockets_2sides.jpg`, `reports/C6_sockets_3sides.jpg`", "- **Result: OK**", ""]

    # C7
    _, pieces, prof = load_model()
    tw, nn = twins(pieces, prof)
    rep += ["## C7 — Uniqueness / twins", f"- Shape distance to the closest piece: median {np.median(nn):.2f} u, min {nn.min():.2f} u",
            "| Piece | Piece | Distance (u) |", "|---|---|---|"] + [f"| {a} | {b} | {d:.2f} |" for a, b, d in tw]
    rep += ["- **Result: each piece has a distinct shape**; close pairs will be settled by the neighbours.", ""]

    # C8
    fus = load_json(os.path.join(DATA, "fusion.json"))
    nv = collections.Counter(len(r["views"]) for r in fus)
    sd = [s for r in fus for s in r["sides"]]
    multi = sum(1 for s in sd if len(s["kept"]) >= 2)
    per_photo = collections.defaultdict(list)
    for p in P:
        for v in p["views"]:
            if v["weight"] > 0:
                per_photo[v["file"]].append(v["fusion_deviation_u"])
    rejected = [(p["id"], v["file"]) for p in P for v in p["views"] if not v["kept"]]
    rep += ["## C8 — Fusion of the views", f"- Views per piece: {dict(sorted(nv.items()))} (every piece has at least 2 views)",
            f"- Sides averaged over ≥ 2 views: {multi} / {len(sd)}; otherwise the most reliable view alone",
            "| Photo | views | median deviation to the fused piece (u) | p90 |", "|---|---|---|---|"]
    rep += [f"| `{f}` | {len(e)} | {np.median(e):.2f} | {np.percentile(e, 90):.2f} |" for f, e in per_photo.items()]
    rep += [f"- Views dropped entirely ({len(rejected)}): {', '.join(f'{a} ({b.split(chr(47))[-1]})' for a, b in rejected)}",
            f"- Alerts: { {f: sum(f in p['flags'] for p in P) for f in ['single_view', 'side_unconfirmed', 'types_differ_between_views']} }"]
    ev_path = os.path.join(DATA, "evaluation.json")
    if os.path.exists(ev_path):
        rep += ["- Evaluation against the board (`src/evaluation.py`, typical piece ↔ socket deviation σ, lower = more accurate shapes):"]
        rep += [f"  - {k}: σ = {v['sigma_u']:.2f} u" for k, v in load_json(ev_path).items()]
    rep += ["- **Result: OK**", ""]

    # C9
    pl = load_json(os.path.join(DATA, "placements.json"))
    rep += ["## C9 — Accuracy of the proposals"]
    if not pl["placed"] and not pl.get("excluded"):
        rep += ["- Waiting for the first trials (no placement nor exclusion in `data/placements.json`).", ""]
    else:
        rep += [f"- Confirmed placements: {len(pl['placed'])}; failed trials: {len(pl.get('excluded', []))}"]
        rep += calibration(pl) + [""]
    with open(os.path.join(REPORTS, "checks_report.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(rep))
    print("\n".join(rep))


def calibration(pl):
    """Crosses the proposed waves (reports/wave_N.json) with the real trials: success by reliability and by %."""
    ok = {(p["cell"], p["piece"]) for p in pl["placed"]}
    ko = {tuple(e.split(":")) for e in pl.get("excluded", [])}
    rows = []
    for f in sorted(glob.glob(os.path.join(REPORTS, "wave_*.json"))):
        for p in load_json(f)["proposals"]:
            c = p["candidates"][0]
            res = "OK" if (p["cell"], c["piece"]) in ok else ("KO" if (p["cell"], c["piece"]) in ko else None)
            if res:
                rows.append((c.get("stability") or 0, c["pct_cell"], res == "OK"))
    if not rows:
        return ["- No first choice of a wave tried yet."]
    out = [f"- First choices of the waves tried: {len(rows)}, successful: {sum(r[2] for r in rows)} ({100 * np.mean([r[2] for r in rows]):.0f} %)",
           "", "| Group | Trials | Successful | Rate |", "|---|---|---|---|"]
    for name, sel in [("reliability 9/9", lambda r: r[0] >= 0.99), ("reliability < 9/9", lambda r: r[0] < 0.99),
                      ("engine % ≥ 80", lambda r: r[1] >= 80), ("engine % 50–80", lambda r: 50 <= r[1] < 80),
                      ("engine % < 50", lambda r: r[1] < 50)]:
        g = [r for r in rows if sel(r)]
        if g:
            out.append(f"| {name} | {len(g)} | {sum(r[2] for r in g)} | {100 * np.mean([r[2] for r in g]):.0f} % |")
    return out


if __name__ == "__main__":
    main()
